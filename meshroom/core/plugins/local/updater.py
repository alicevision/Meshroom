import logging
import os
import shutil

from typing import List, Optional, Tuple
from pathlib import Path, PurePosixPath

from meshroom.env import EnvVar
from meshroom.core.plugins import isValidPluginName, meshroomPluginsFolder, meshroomPluginsInternalPrefix
from meshroom.core.plugins.metadata import PluginInstalledAsset, PluginMetadata
from meshroom.core.plugins.record import PluginRecord
from meshroom.core.plugins.provider import PluginProvider
from meshroom.core.plugins.local.service import PluginService
from meshroom.core.plugins.local.installer import PluginInstaller, listFiles
from meshroom.core.plugins.local.uninstaller import PluginUninstaller

# The files generated in the plugin folder by its installation, which are not carried over to the new version.
_GENERATED_FILES = ("plugin.lock", "uv.lock")
# The folder of the plugin's environment, generated by its installation.
_ENVIRONMENT_FOLDER = "venv"
# The folders of compiled Python modules, at any depth.
_CACHE_FOLDER = "__pycache__"
# The suffix of a carried over file whose path is taken by a file of the new version.
_PREVIOUS_SUFFIX = ".previous"


class PluginUpdater(PluginService):
    """
    Updates a local plugin by installing a new version of it in place of the installed one:
        1. Move the installed plugin aside, to "<pluginsPath>/<internalPrefix><pluginName>".
        2. Install the new version with a PluginInstaller, which moves the unchanged assets of the
           installed plugin (same path and same sha256) instead of downloading them again.
        3. Carry over the files added to the installed plugin (e.g. by hand): the files that are neither
           in the archive of the installed version, nor its assets, nor generated by its installation.
        4. Remove the moved plugin with a PluginUninstaller.

    If the update fails or is cancelled, the installed plugin is put back as it was.

    The new version may be named differently from the installed plugin (e.g. a renamed plugin): it is then
    installed in its own folder, in place of the installed one.
    """

    def __init__(self, provider: PluginProvider, record: PluginRecord,
                 version: Optional[str] = None, pluginsPath: Path = meshroomPluginsFolder,
                 installedName: Optional[str] = None) -> None:
        """
        Args:
            provider: the PluginProvider to download the new version of the plugin from.
            record: the record describing the plugin to update.
            version: the version to install, or the version of "record" if None.
            pluginsPath: the folder the plugin is installed in.
            installedName: the name of the folder of the installed plugin, or the name of "record" if None.
        """
        super().__init__("update", installedName or record.name, Path(pluginsPath))
        self._provider: PluginProvider = provider
        self._record: PluginRecord = record
        self._version: Optional[str] = version
        self._backupName: str = f"{meshroomPluginsInternalPrefix}{self._pluginName}"

    def _run(self) -> None:
        """
        Update the plugin: move it aside, install its new version, carry over the files added to it,
        then remove the moved plugin.
        """
        if not EnvVar.get(EnvVar.MESHROOM_LOCAL_PLUGINS):
            raise self._error("Verification", "Local plugin management is disabled.")

        # Check the name is a plain folder name, as the folder to move must be inside of "pluginsPath".
        if not isValidPluginName(self._pluginName):
            raise self._error("Verification", f"Invalid plugin name '{self._pluginName}'.")

        # Check the plugin is installed.
        pluginFolder = self._requireInstalledFolder()
        # How the installed plugin was installed, unknown without its "plugin.lock".
        installed = PluginMetadata.loadJson(pluginFolder / "plugin.lock") or PluginMetadata()

        # Remove the backup a previous update may have left behind.
        backupFolder = self._pluginsPath / self._backupName
        if backupFolder.exists():
            self._removeBackup()

        # Check if the user canceled the service.
        self._checkCancel()

        # Move the installed plugin aside: this frees its folder for the installer.
        # A rename keeps the plugin's environment ("venv") usable when it is moved back.
        self._reportProgress("Backing up the installed plugin", 0.0)
        try:
            pluginFolder.rename(backupFolder)
        except OSError as exc:
            raise self._error("Backup", f"Failed to move '{pluginFolder}' to '{backupFolder}'.", exc)

        installer = PluginInstaller(self._provider, self._record, self._version, self._pluginsPath,
                                    self._reusableAssets(installed, backupFolder))
        try:
            # The removal of the backup is fast, the progress is the one of the installer.
            installer.execute(self._reportProgress, self._isCancelled)
        except BaseException:
            # The installer removes what it has installed and moves back the assets it reused,
            # put the previous version back.
            self._restoreBackup(pluginFolder, backupFolder)
            raise

        self._reportProgress("Carrying over the files added to the plugin", 1.0)
        carriedFiles: List[Tuple[Path, Path]] = []
        try:
            self._carryOverAddedFiles(installed, backupFolder, installer, carriedFiles)
        except OSError as exc:
            # Put the previous version back as it was.
            self._moveBack(carriedFiles)
            installer.restoreReusedAssets()
            shutil.rmtree(installer.pluginFolder, ignore_errors=True)
            self._restoreBackup(pluginFolder, backupFolder)
            raise self._error("Files", "Failed to carry over the files added to the plugin.", exc)

        # The update is done, failing to remove the backup is not an error.
        self._reportProgress("Removing the previous version", 1.0)
        try:
            self._removeBackup()
        except Exception as exc:
            logging.warning(f"Plugin '{self._pluginName}' updated, but its backup '{backupFolder}' "
                            f"could not be removed: {exc}")

        self._reportProgress("Plugin updated", 1.0)
        logging.info(f"Plugin '{self._pluginName}' updated in '{installer.pluginFolder}'")

    def _reusableAssets(self, installed: PluginMetadata, backupFolder: Path) -> List[Tuple[PluginInstalledAsset, Path]]:
        """
        Return the assets of the installed plugin, with their location in "backupFolder".

        Args:
            installed: the metadata from the "plugin.lock" of the installed plugin.
            backupFolder: the folder the installed plugin has been moved to.
        """
        installedAssets = installed.installedAssets
        if installedAssets is None:
            # Installed before the installed assets were recorded: the declared assets with a sha256
            # were checked against it when they were downloaded.
            installedAssets = [PluginInstalledAsset(asset.name, asset.path, asset.url, asset.sha256)
                               for asset in installed.assets if asset.url is not None and asset.sha256 is not None]

        resolvedBackupFolder = backupFolder.resolve()
        reusableAssets = []
        for installedAsset in installedAssets:
            location = backupFolder.joinpath(*PurePosixPath(installedAsset.path).parts)
            # Guard against a path escaping the plugin folder (e.g. through a symbolic link).
            if location.parent.resolve().is_relative_to(resolvedBackupFolder):
                reusableAssets.append((installedAsset, location))
        return reusableAssets

    def _carryOverAddedFiles(self, installed: PluginMetadata, backupFolder: Path, installer: PluginInstaller,
                             carriedFiles: List[Tuple[Path, Path]]) -> None:
        """
        Move the files added to the installed plugin from "backupFolder" to the folder of the new version.

        A file whose path is taken by a file of the new version is moved next to it, with the suffix
        "_PREVIOUS_SUFFIX". A file in the path of an asset of the new version is not carried over: the
        asset owns its path.

        Args:
            installed: the metadata from the "plugin.lock" of the installed plugin.
            backupFolder: the folder the installed plugin has been moved to.
            installer: the installer of the new version, once it has installed it.
            carriedFiles: filled with the moved files, as (new location, previous location).

        Raises:
            OSError: if a file cannot be moved.
        """
        if installed.files is None:
            logging.warning(f"Plugin '{self._pluginName}' was installed without the list of its files: "
                            f"the files added to it are not carried over to the new version.")
            return

        knownFiles = set(installed.files).union(_GENERATED_FILES)
        installedAssetPaths = [asset.path for asset in installed.assets]
        installedAssetPaths += [asset.path for asset in installed.installedAssets or []]
        newAssetPaths = [asset.path for asset in installer.metadata.assets]

        for relativePath in listFiles(backupFolder, _isGeneratedFolder):
            if relativePath in knownFiles or _isInPaths(relativePath, installedAssetPaths):
                continue
            if _isInPaths(relativePath, newAssetPaths):
                logging.warning(f"File '{relativePath}' added to plugin '{self._pluginName}' is in the path of an "
                                f"asset of the new version, it is not carried over.")
                continue

            destination = installer.pluginFolder.joinpath(*PurePosixPath(relativePath).parts)
            if not _isFreePath(destination, installer.pluginFolder):
                destination = destination.with_name(destination.name + _PREVIOUS_SUFFIX)
                if not _isFreePath(destination, installer.pluginFolder):
                    logging.warning(f"File '{relativePath}' added to plugin '{self._pluginName}' conflicts with "
                                    f"the files of the new version, it is not carried over.")
                    continue
                logging.warning(f"File '{relativePath}' added to plugin '{self._pluginName}' is replaced by the "
                                f"new version, carried over as '{destination.name}'.")

            source = backupFolder.joinpath(*PurePosixPath(relativePath).parts)
            destination.parent.mkdir(parents=True, exist_ok=True)
            os.rename(source, destination)
            carriedFiles.append((destination, source))

        if carriedFiles:
            logging.info(f"{len(carriedFiles)} file(s) added to plugin '{self._pluginName}' carried over to the new version.")

    @staticmethod
    def _moveBack(movedFiles: List[Tuple[Path, Path]]) -> None:
        """ Move the files moved by _carryOverAddedFiles back to their previous location. """
        for destination, source in reversed(movedFiles):
            try:
                os.rename(destination, source)
            except OSError as exc:
                logging.error(f"Failed to move '{destination}' back to '{source}': {exc}")

    def _removeBackup(self) -> None:
        """ Remove the backup folder of the plugin, with a PluginUninstaller. """
        PluginUninstaller(self._backupName, self._pluginsPath).execute()

    def _restoreBackup(self, pluginFolder: Path, backupFolder: Path) -> None:
        """
        Move the backup folder back to the plugin folder.

        Args:
            pluginFolder: the folder of the plugin.
            backupFolder: the folder the installed plugin has been moved to.
        """
        try:
            backupFolder.rename(pluginFolder)
        except OSError as exc:
            logging.error(f"Failed to restore plugin '{self._pluginName}': move '{backupFolder}' back to '{pluginFolder}' "
                          f"manually. ({exc})")


def _isGeneratedFolder(relativePath: str) -> bool:
    """ Return whether the folder "relativePath" of a plugin is generated: its environment, or compiled Python modules. """
    return relativePath == _ENVIRONMENT_FOLDER or PurePosixPath(relativePath).name == _CACHE_FOLDER


def _isInPaths(relativePath: str, paths: List[str]) -> bool:
    """ Return whether the POSIX path "relativePath" is one of "paths", or inside of one of them. """
    return any(relativePath == path or relativePath.startswith(path + "/") for path in paths)


def _isFreePath(path: Path, folder: Path) -> bool:
    """ Return whether a file can be created at "path" in "folder": nothing exists there, nor in place of its folders. """
    if os.path.lexists(path):
        return False
    parent = path.parent
    while parent != folder:
        if os.path.lexists(parent):
            return parent.is_dir() and not parent.is_symlink()
        parent = parent.parent
    return True
