import argparse
import os

parser = argparse.ArgumentParser(description='Generate the Python dictionary of the MaterialIcons from a codepoints file.\n'
                                'An example of codepoints file for MaterialIcons: https://github.com/google/material-design-icons/blob/master/font/MaterialIcons-Regular.codepoints.')
parser.add_argument('codepoints', type=str, help='Codepoints file.')
defaultOutput = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'components', 'materialIconsData.py')
parser.add_argument('--output', type=str, default=defaultOutput,
                    help='Generated Python file (default: meshroom/ui/components/materialIconsData.py).')

args = parser.parse_args()

# Override icons with problematic names
mapping = {
    'delete': 'delete_',
    'class': 'class_',
    '3d_rotation': '_3d_rotation',
    'opacity': 'opacity_',
    'transform': 'transform_',
    'print': 'print_',
    'public': 'public_',
    'password': 'pwd',
    'wifi_password': 'wifi_pwd',
    'try': 'try_'
}

# Override icons that are numeric literals
numeric_literals = ['1', '2', '3', '4', '5', '6', '7', '8', '9']

# List of existing name to override potential duplicates
names = []

with open(args.output, 'w') as py_file:
    py_file.write('""" MaterialIcons names and glyphs, exposed to QML as "MaterialIcons" (see materialIcons.py).\n\n')
    py_file.write('Generated by meshroom/ui/qml/MaterialIcons/generate_material_icons.py from the font codepoints:'
                  ' do not edit.\n')
    py_file.write('"""\n\n')
    py_file.write('MATERIAL_ICONS = {\n')

    with open(args.codepoints, 'r') as codepoints:
        for line in codepoints.readlines():
            name, code = line.strip().split(" ")
            name = mapping.get(name, name)

            # Add underscore to names that are numeric literals (e.g. "123" will become "_123")
            if name[0] in numeric_literals:
                name = "_" + name

            # If the name already exists in the list, append an index
            if name in names:
                index = 2
                while name + str(index) in names:
                    index = index + 1
                name = name + str(index)

            names.append(name)
            # Codepoints beyond the Basic Multilingual Plane need the 8-digit escape
            escape = f'\\u{int(code, 16):04x}' if int(code, 16) <= 0xFFFF else f'\\U{int(code, 16):08x}'
            py_file.write(f'    "{name}": "{escape}",\n')
        py_file.write('}\n')
